import aiResponseDecoration from '../../../assets/decorations/AIResponse.svg'
import yourMemoryDecoration from '../../../assets/decorations/YourMemory.svg'
import EvidenceExcerpts from '../../memory/EvidenceExcerpts/EvidenceExcerpts.jsx'
import WorkingRecipe from '../../memory/WorkingRecipe/WorkingRecipe.jsx'
import GardenMemoryMap from '../../garden/GardenMemoryMap/GardenMemoryMap.jsx'

const decisionLabels = {
  kept: 'Kept as a prompt',
  edited: 'Edited by user',
  rejected: 'Rejected by user',
}

function formatCreatedAt(createdAt) {
  const date = new Date(createdAt)

  if (Number.isNaN(date.getTime())) {
    return 'Date unavailable'
  }

  return new Intl.DateTimeFormat('en-ZA', {
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(date)
}

function ArchiveEntry({ entry }) {
  const titleId = `archive-entry-${entry.id}`
  const hasConversation = Array.isArray(entry.memoryFragments)
  let decisionLabel = decisionLabels[entry.decision] || 'Decision unavailable'

  if (entry.decision === 'kept' && entry.domain === 'garden') {
    decisionLabel = 'AI response kept as a prompt'
  } else if (entry.decision === 'edited' && entry.domain === 'garden') {
    decisionLabel = 'User note added to AI response'
  } else if (entry.decision === 'rejected' && entry.domain === 'garden') {
    decisionLabel = 'AI response rejected by user'
  } else if (entry.decision === 'kept' && entry.domain === 'ritual') {
    decisionLabel = 'AI response kept as a prompt'
  } else if (entry.decision === 'edited' && entry.domain === 'ritual') {
    decisionLabel = 'User note added to AI response'
  } else if (entry.decision === 'rejected' && entry.domain === 'ritual') {
    decisionLabel = 'AI response rejected by user'
  } else if (entry.decision === 'kept' && entry.workingRecipe) {
    decisionLabel = 'Kept as a working reconstruction'
  }

  return (
    <article className="archive-entry" aria-labelledby={titleId}>
      <header>
        <p>{decisionLabel}</p>
        <h2 id={titleId}>{entry.cardTitle || 'Kitchen memory trace'}</h2>
        {entry.isExample ? (
          <p>Demonstration conversation</p>
        ) : (
          <p>
            <time dateTime={entry.createdAt}>
              {formatCreatedAt(entry.createdAt)}
            </time>
          </p>
        )}
      </header>

      {hasConversation ? (
        entry.domain === 'garden' ? (
          <>
            <GardenMemoryMap
              fragments={entry.memoryFragments}
              id={`${titleId}-memory-map`}
              title="Saved Garden memory map"
            />
            <section
              className="archive-garden-responses"
              aria-labelledby={`${titleId}-responses-title`}
            >
              <h3 id={`${titleId}-responses-title`}>Provisional AI responses</h3>
              {entry.aiResponses?.map((response, index) => (
                <details key={`${titleId}-response-${index + 1}`}>
                  <summary>View provisional AI response {index + 1}</summary>
                  <section>
                    <h4>Provisional AI reflection</h4>
                    <p>{response.reflection}</p>
                  </section>
                  <EvidenceExcerpts items={response.evidence} />
                  {response.limitation && (
                    <section className="ai-response__section ai-response__section--limitation">
                      <h4>AI-generated note about possible gaps</h4>
                      <p>{response.limitation}</p>
                      <p className="ai-response__disclosure">
                        This note was generated by the AI. It may miss gaps in
                        your memory. Check it against your own fragments.
                      </p>
                    </section>
                  )}
                  <section>
                    <h4>AI question</h4>
                    {response.editorialNote && (
                      <p className="archive-conversation__editorial-note" role="note">
                        {response.editorialNote}
                      </p>
                    )}
                    <p>{response.question}</p>
                  </section>
                </details>
              ))}
            </section>
          </>
        ) : entry.domain === 'ritual' ? (
          <>
            <section
              className="archive-ritual-sequence"
              aria-labelledby={`${titleId}-sequence-title`}
            >
              <h3 id={`${titleId}-sequence-title`}>Your remembered sequence</h3>
              <p>
                This order reflects how you arranged these moments. It is not
                presented as a definitive account of your family practice.
              </p>
              <ol className="ritual-sequence__list">
                {(entry.ritualSequence?.orderedMoments ||
                  entry.memoryFragments.map((fragment) => fragment.text)
                ).map((text, index) => (
                  <li className="ritual-moment" key={`${titleId}-ordered-${index}`}>
                    <span className="ritual-moment__label">Moment {index + 1}</span>
                    <p>{text}</p>
                  </li>
                ))}
              </ol>
              {entry.ritualSequence?.unplacedMoments?.length > 0 && (
                <section className="ritual-sequence__open">
                  <h4>Order not remembered</h4>
                  <ul className="ritual-sequence__list">
                    {entry.ritualSequence.unplacedMoments.map((text, index) => (
                      <li className="ritual-moment" key={`${titleId}-open-${index}`}>
                        <p>{text}</p>
                      </li>
                    ))}
                  </ul>
                </section>
              )}
            </section>
            <section
              className="archive-ritual-responses"
              aria-labelledby={`${titleId}-responses-title`}
            >
              <h3 id={`${titleId}-responses-title`}>Provisional AI responses</h3>
              {entry.aiResponses?.map((response, index) => (
                <details key={`${titleId}-response-${index + 1}`}>
                  <summary>View provisional AI response {index + 1}</summary>
                  <section>
                    <h4>Provisional AI reflection</h4>
                    <p>{response.reflection}</p>
                  </section>
                  <EvidenceExcerpts items={response.evidence} />
                  {response.limitation && (
                    <section className="ai-response__section ai-response__section--limitation">
                      <h4>AI-generated note about possible gaps</h4>
                      <p>{response.limitation}</p>
                      <p className="ai-response__disclosure">
                        This note was generated by the AI. It may miss gaps in
                        your memory. Check it against your own fragments.
                      </p>
                    </section>
                  )}
                  <section>
                    <h4>AI question</h4>
                    <p>{response.question}</p>
                  </section>
                </details>
              ))}
            </section>
          </>
        ) : (
        <div className="archive-conversation">
          {entry.memoryFragments.map((fragment, index) => {
            const response = entry.aiResponses?.[index]
            const fragmentId = `${titleId}-fragment-${index + 1}`

            return (
              <div className="archive-conversation__turn" key={fragmentId}>
                <section
                  className="archive-entry__user-content"
                  aria-labelledby={fragmentId}
                >
                  <img
                    className="archive-entry__decoration"
                    src={yourMemoryDecoration}
                    alt=""
                    aria-hidden="true"
                  />
                  <h3 id={fragmentId}>User memory fragment {index + 1}</h3>
                  <p>{fragment.text}</p>
                  {fragment.questionAnswered && (
                    <p className="archive-conversation__context">
                      Answered AI question: {fragment.questionAnswered}
                    </p>
                  )}
                </section>

                {response && (
                  <details className="archive-conversation__ai-response">
                    <summary>
                      <img
                        className="archive-entry__ai-decoration"
                        src={aiResponseDecoration}
                        alt=""
                        aria-hidden="true"
                      />
                      <span>View provisional AI response {index + 1}</span>
                    </summary>
                    <section>
                      <h3>Provisional AI reflection</h3>
                      <p>{response.reflection}</p>
                    </section>
                    <EvidenceExcerpts items={response.evidence} />
                    {response.limitation && (
                      <section className="ai-response__section ai-response__section--limitation">
                        <h3>AI-generated note about possible gaps</h3>
                        <p>{response.limitation}</p>
                        <p className="ai-response__disclosure">
                          This note was generated by the AI. It may miss gaps
                          in your memory. Check it against your own fragments.
                        </p>
                      </section>
                    )}
                    <section>
                      <h3>AI question</h3>
                      {response.editorialNote && (
                        <p
                          className="archive-conversation__editorial-note"
                          role="note"
                        >
                          {response.editorialNote}
                        </p>
                      )}
                      <p>{response.question}</p>
                    </section>
                  </details>
                )}
              </div>
            )
          })}
        </div>
        )
      ) : (
        <section
          className="archive-entry__user-content"
          aria-labelledby={`${titleId}-memory`}
        >
          <img
            className="archive-entry__decoration"
            src={yourMemoryDecoration}
            alt=""
            aria-hidden="true"
          />
          <h3 id={`${titleId}-memory`}>Your memory</h3>
          <p>{entry.userMemory}</p>
        </section>
      )}

      {entry.workingRecipe && (
        <WorkingRecipe
          id={`${titleId}-working-recipe`}
          recipe={entry.workingRecipe}
        />
      )}

      {entry.userRevision && (
        <section
          className="archive-entry__user-content"
          aria-labelledby={`${titleId}-revision`}
        >
          <img
            className="archive-entry__decoration"
            src={yourMemoryDecoration}
            alt=""
            aria-hidden="true"
          />
          <h3 id={`${titleId}-revision`}>
            {entry.domain === 'garden' || entry.domain === 'ritual'
              ? 'Your note'
              : 'Your version'}
          </h3>
          <p>{entry.userRevision}</p>
        </section>
      )}

      {entry.userCorrection && (
        <section
          className="archive-entry__user-content"
          aria-labelledby={`${titleId}-correction`}
        >
          <img
            className="archive-entry__decoration"
            src={yourMemoryDecoration}
            alt=""
            aria-hidden="true"
          />
          <h3 id={`${titleId}-correction`}>
            {entry.domain === 'garden' || entry.domain === 'ritual'
              ? 'Your correction'
              : 'Your family correction'}
          </h3>
          <p>{entry.userCorrection}</p>
        </section>
      )}

      {!hasConversation && <details>
        <summary>
          <img
            className="archive-entry__ai-decoration"
            src={aiResponseDecoration}
            alt=""
            aria-hidden="true"
          />
          <span>View provisional AI response</span>
        </summary>

        <section aria-labelledby={`${titleId}-ai-reflection`}>
          <h3 id={`${titleId}-ai-reflection`}>Provisional AI reflection</h3>
          <p>{entry.aiReflection}</p>
        </section>

        <section aria-labelledby={`${titleId}-ai-limitation`}>
          <h3 id={`${titleId}-ai-limitation`}>
            AI-generated note about possible gaps
          </h3>
          <p>{entry.aiLimitation}</p>
          <p className="ai-response__disclosure">
            This note was generated by the AI. It may miss gaps in your memory.
            Check it against your own fragments.
          </p>
        </section>

        <section aria-labelledby={`${titleId}-ai-question`}>
          <h3 id={`${titleId}-ai-question`}>AI question</h3>
          <p>{entry.aiQuestion}</p>
        </section>
      </details>}
    </article>
  )
}

export default ArchiveEntry
